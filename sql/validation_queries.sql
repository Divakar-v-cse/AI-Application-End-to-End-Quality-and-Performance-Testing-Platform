-- ----------------------------------------------------------------------------
-- [01/15] db.users.unique_email  (table: users, severity: critical)
-- User emails are unique. No duplicate email addresses exist across accounts.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT email, COUNT(*) AS occurrences FROM users GROUP BY email HAVING COUNT(*) > 1;

-- ----------------------------------------------------------------------------
-- [02/15] db.results.orphans  (table: test_results, severity: critical)
-- Every test result belongs to a run. Referential integrity between results and runs.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT r.id, r.case_key FROM test_results r LEFT JOIN test_runs t ON t.id = r.run_id WHERE t.id IS NULL;

-- ----------------------------------------------------------------------------
-- [03/15] db.runs.required_fields  (table: test_runs, severity: major)
-- Runs have non-null required fields. run_key, status and started_at must always be populated.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id FROM test_runs WHERE run_key IS NULL OR TRIM(run_key) = '' OR status IS NULL OR started_at IS NULL;

-- ----------------------------------------------------------------------------
-- [04/15] db.results.status_domain  (table: test_results, severity: major)
-- Test result statuses are in the allowed domain. Only passed/failed/skipped/error are valid statuses.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id, status FROM test_results WHERE status NOT IN ('passed','failed','skipped','error');

-- ----------------------------------------------------------------------------
-- [05/15] db.runs.duplicate_keys  (table: test_runs, severity: critical)
-- Run keys are unique. Duplicate run keys would corrupt historical reporting.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT run_key, COUNT(*) AS occurrences FROM test_runs GROUP BY run_key HAVING COUNT(*) > 1;

-- ----------------------------------------------------------------------------
-- [06/15] db.cases.duplicate_keys  (table: test_cases, severity: major)
-- Test case keys are unique. Catalog keys are the join key for results and ingestion.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT key, COUNT(*) AS occurrences FROM test_cases GROUP BY key HAVING COUNT(*) > 1;

-- ----------------------------------------------------------------------------
-- [07/15] db.eval.score_range  (table: evaluation_results, severity: critical)
-- AI evaluation scores are within 0-100. Out-of-range scores break evaluation reporting and gates.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id, score FROM evaluation_results WHERE score < 0 OR score > 100;

-- ----------------------------------------------------------------------------
-- [08/15] db.eval.integrity  (table: evaluation_results, severity: major)
-- AI evaluations reference a real conversation. Each evaluation must map to at least one stored chat message.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT e.id, e.conversation_id FROM evaluation_results e
           WHERE e.conversation_id <> ''
             AND NOT EXISTS (SELECT 1 FROM chat_messages m WHERE m.conversation_id = e.conversation_id);

-- ----------------------------------------------------------------------------
-- [09/15] db.api.status_range  (table: api_metrics, severity: major)
-- API metric status codes are valid HTTP codes. Status codes must fall inside 100-599.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id, status_code FROM api_metrics WHERE status_code < 100 OR status_code > 599;

-- ----------------------------------------------------------------------------
-- [10/15] db.metrics.latency_positive  (table: api_metrics, severity: major)
-- Latency measurements are positive. Zero or negative latencies indicate broken instrumentation.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id, response_time_ms FROM api_metrics WHERE response_time_ms <= 0;

-- ----------------------------------------------------------------------------
-- [11/15] db.pages.load_positive  (table: page_metrics, severity: major)
-- Page load timings are positive. Page load and TTFB must be greater than zero.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id, load_time_ms FROM page_metrics WHERE load_time_ms <= 0 OR ttfb_ms < 0;

-- ----------------------------------------------------------------------------
-- [12/15] db.load.consistency  (table: load_test_runs, severity: major)
-- Load test aggregates are consistent. Failures cannot exceed requests and error rate stays 0-100.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id FROM load_test_runs WHERE failures > requests OR error_rate < 0 OR error_rate > 100;

-- ----------------------------------------------------------------------------
-- [13/15] db.runs.time_order  (table: test_runs, severity: minor)
-- Run timestamps are ordered. finished_at can never precede started_at.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id FROM test_runs WHERE finished_at IS NOT NULL AND finished_at < started_at;

-- ----------------------------------------------------------------------------
-- [14/15] db.chat.role_domain  (table: chat_messages, severity: minor)
-- Chat message roles are valid. Only user/assistant/system roles are stored.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id, role FROM chat_messages WHERE role NOT IN ('user','assistant','system');

-- ----------------------------------------------------------------------------
-- [15/15] db.metrics.orphans  (table: api_metrics, severity: minor)
-- API metrics reference an existing run. Dangling run ids break drill-down navigation.
-- Pass criterion: 0 rows returned.
-- ----------------------------------------------------------------------------
SELECT id FROM api_metrics WHERE run_id IS NOT NULL AND run_id NOT IN (SELECT id FROM test_runs);

