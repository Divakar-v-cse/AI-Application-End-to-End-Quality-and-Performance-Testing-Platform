"""Regenerate ``sql/validation_queries.sql`` from the executable check catalog.

``app.services.checks.DB_CHECKS`` is the single source of truth: the same SQL
strings are executed by ``pytest``, by ``POST /api/data-quality/run`` and by the
generated ``.sql`` file. Run this after editing the catalog::

    python scripts/gen_sql_queries.py

``tests/db/test_validation_queries.py`` fails if the file drifts from the code.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.services.checks import DB_CHECKS  # noqa: E402  (path bootstrap above)

OUTPUT = ROOT / "sql" / "validation_queries.sql"

HEADER = """\
-- ============================================================================
-- AI Quality Platform - SQL data-validation queries
-- ============================================================================
-- Each statement returns the offending rows for one rule: a check passes when
-- the query returns zero rows. The same statements are executed by
--   * pytest                (tests/db/test_validation_queries.py)
--   * the API               (POST /api/data-quality/run)
--   * CI                    (scripts/evaluate_gates.py)
-- and can be run by hand with any SQL client:
--   sqlite3 backend/data/quality.db < sql/validation_queries.sql
--
-- Generated by scripts/gen_sql_queries.py from backend/app/services/checks.py
-- (DB_CHECKS). Do not edit by hand - the test suite asserts byte-level
-- agreement with the catalog.
--
-- Categories covered: missing records, duplicate records, invalid data types,
-- null values, referential/data consistency and AI evaluation integrity.
-- ============================================================================

"""


def render() -> str:
    total = len(DB_CHECKS)
    parts = [HEADER]
    for index, check in enumerate(DB_CHECKS, start=1):
        bar = "-- " + "-" * 76
        parts.append(bar + "\n")
        parts.append(f"-- [{index:02d}/{total}] {check.key}  (table: {check.table}, severity: {check.severity})\n")
        parts.append(f"-- {check.name}. {check.description}\n")
        parts.append(f"-- Pass criterion: 0 rows returned.\n")
        parts.append(bar + "\n")
        parts.append(check.sql.strip().rstrip(";") + ";\n\n")
    return "".join(parts)


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {len(DB_CHECKS)} checks to {OUTPUT}")


if __name__ == "__main__":
    main()
